// Writes public/_redirects (Netlify's edge redirect file) from
// legacy-redirects.json before every build (npm "prebuild").
//
// Why: redirects defined only in next.config.ts run inside Netlify's
// Next.js server function, so every hit on an old renuforyou.com URL (from
// Google, backlinks, bookmarks) cost a function call. Netlify applies
// _redirects at its CDN edge before any function runs — same redirects,
// near-zero cost. next.config.ts keeps the same list as a fallback and for
// local `npm run dev`, which doesn't read _redirects.
//
// public/_redirects is generated — edit legacy-redirects.json instead.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
const legacy = JSON.parse(fs.readFileSync(path.join(root, 'legacy-redirects.json'), 'utf8'));

const lines = [
  '# GENERATED by scripts/write-netlify-redirects.mjs from legacy-redirects.json — do not edit by hand.',
  '',
  '# Booking moved to Decoda Health (same URL as BOOKING_URL in src/data/site-data.ts)',
  '/book   https://app.decodahealth.com/renu/self-schedule   302',
  '/book/  https://app.decodahealth.com/renu/self-schedule   302',
  '# Shop removed from the public site',
  '/shop   /   302',
  '/shop/  /   302',
  '',
  `# ${legacy.length} old WordPress URLs → their closest new page (permanent)`
];
for (const { source, destination } of legacy) {
  lines.push(`${source}  ${destination}  301`);
  // Old URLs were indexed both with and without a trailing slash; one
  // rule per form so each lands on its new page in a single hop.
  if (!/\.[a-z]+$/i.test(source)) lines.push(`${source}/  ${destination}  301`);
}

fs.writeFileSync(path.join(root, 'public', '_redirects'), lines.join('\n') + '\n');
console.log(`public/_redirects: ${legacy.length} legacy redirects (+ /book, /shop)`);
